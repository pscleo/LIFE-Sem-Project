"""
================================================================================
FILE RENAMING UTILITY - OCTAHEDRON CONSTELLATION DATA
================================================================================

Module: rename_octahedron_files.py
Status: One-time utility (run as needed for file reorganization)

PURPOSE
-------
Renames octahedron constellation data files from an older naming convention to
the current standard format. Used when transitioning between file organization
schemes or consolidating data from different simulation runs.

SCOPE
-----
Processes CSV and TXT files in two directories:
  - data-export/maneuver-summaries/
  - data-export/temp/

Only affects files matching the old naming pattern; other files are ignored.

NAMING CONVENTION CHANGE
------------------------
Old Format (deprecated):
  Octahedron_{direction}_{SK_interval}_{distance}.{ext}
  Examples:
    Octahedron_Xm_SK14d_1000m.csv
    Octahedron_Yp_SK7d_1000m.txt
    Octahedron_Zm_SK1h_1000m.csv

New Format (current standard):
  Octahedron_{SK_interval}_{direction}{distance}.{ext}
  Examples:
    Octahedron_SK14d_Xm1000m.csv
    Octahedron_SK7d_Yp1000m.txt
    Octahedron_SK1h_Zm1000m.csv

Why the change?
  - SK interval is now the primary sort key (easier data organization)
  - Matches octahedron-constellation.py's file generation format
  - Enables consistency with analysis-SK-duration.py expectations
  - Enables natural alphabetical sorting by SK interval

FILENAME STRUCTURE
------------------
Octahedron_{SK_interval}_{axis}{sign}{distance}

Components:
  - SK_interval: SK0p5h, SK1h, SK3h, SK6h, SK12h, SK1d, SK3d, SK7d, SK14d, SK28d
  - axis:        X, Y, or Z (coordinate axis)
  - sign:        p (plus/+) or m (minus/-)
  - distance:    Offset from nominal position (e.g., 1000m)

Example breakdown:
  Octahedron_SK7d_Xm1000m
  └─ SK7d:   7-day station-keeping interval
  └─ X:      X-axis offset
  └─ m:      Negative direction
  └─ 1000m:  1000 meter magnitude

HOW IT WORKS
------------
1. Iterates through specified directories
2. Finds all Octahedron_*.csv and Octahedron_*.txt files
3. Parses old format by splitting on underscores (4 parts expected)
4. Reconstructs new format: Octahedron_{SK}_{direction}{distance}
5. Renames file while preserving file extension
6. Prints progress for each rename
7. Reports total files renamed

USAGE
-----
Run this script once after generating old-format files:

  python rename_octahedron_files.py

The script will:
  ✓ Rename all matching files in both directories
  ✓ Display progress for each file
  ✓ Print summary statistics
  ✓ Leave non-matching files untouched

NO COMMAND-LINE ARGUMENTS - runs automatically on execution.

SAFETY NOTES
------------
✓ Safe to run: Uses pathlib (cross-platform compatible)
✓ Non-destructive: Only renames, doesn't delete or modify content
✓ Idempotent: Safe to run again if new old-format files appear
✗ No backup: Original filenames are overwritten (use git if concerned)
✓ Skips unknown files: Only processes matching old-format names

ERROR HANDLING
--------------
If directories don't exist:
  - Prints warning message
  - Continues to next directory
  - No files are created or deleted

If rename fails (e.g., target exists):
  - Python raises exception
  - Previous renames are NOT rolled back
  - Check file permissions if this occurs

WHEN TO USE
-----------
✓ Organizing old data before analysis
✓ Consolidating results from different simulation runs
✓ Migrating between different project versions
✓ One-time data housekeeping task

WHEN NOT TO USE
----------------
✗ Regular workflow (data generated by octahedron-constellation.py is already correct)
✗ Files already in new format (no-op, but harmless)
✗ Custom naming schemes (modify function to match your format)

INTEGRATION WITH PIPELINE
--------------------------
Typical workflow:
  1. Run octahedron-constellation.py → generates new-format files
  2. (Optional) Run this if you have old-format files to migrate
  3. Run analysis-SK-duration.py → expects new format, works correctly

DEPENDENCIES
------------
- pathlib (standard library)
- No external dependencies

CUSTOMIZATION
-------------
To rename files in a different directory:
  - Edit line 5-6 to point to new paths, OR
  - Call rename_files_in_directory() with custom Path object

To change naming pattern:
  - Modify the parsing logic (lines 15-17)
  - Modify the reconstruction logic (lines 23-24)

HISTORY
-------
- Created: During constellation simulation workflow refinement
- Reason:  SK interval moved to primary sort position for better organization
- Status:  One-time utility, archived after use

================================================================================
"""

from pathlib import Path

# Get paths
current_dir = Path(__file__).resolve().parent
summaries_dir = current_dir / "data-export" / "maneuver-summaries"
temp_dir = current_dir / "data-export" / "temp"

def rename_files_in_directory(directory):
    """Rename all Octahedron files from current format to: Octahedron_SK{days}d_{direction}1000m"""
    if not directory.exists():
        print(f"Directory not found: {directory}")
        return
    
    print(f"\nRenaming files in: {directory}")
    rename_count = 0
    
    # Process all Octahedron files
    for file_path in directory.glob("Octahedron_*.csv"):
        filename = file_path.stem
        # Current format: Octahedron_Xm_SK14d_1000m
        # Target format: Octahedron_SK14d_Xm1000m
        
        parts = filename.split('_')
        # parts[0] = 'Octahedron'
        # parts[1] = direction (Xm, Xp, Ym, etc.)
        # parts[2] = 'SK14d'
        # parts[3] = '1000m'
        
        if len(parts) == 4 and parts[0] == 'Octahedron':
            direction = parts[1]  # Xm, Xp, Ym, etc.
            sk_interval = parts[2]  # SK14d, SK7d, etc.
            distance = parts[3]  # 1000m
            
            new_name = f"Octahedron_{sk_interval}_{direction}{distance}"
            new_file_path = file_path.parent / f"{new_name}.csv"
            
            file_path.rename(new_file_path)
            print(f"  ✓ {filename}.csv → {new_name}.csv")
            rename_count += 1
    
    # Process all txt files
    for file_path in directory.glob("Octahedron_*.txt"):
        filename = file_path.stem
        
        parts = filename.split('_')
        
        if len(parts) == 4 and parts[0] == 'Octahedron':
            direction = parts[1]
            sk_interval = parts[2]
            distance = parts[3]
            
            new_name = f"Octahedron_{sk_interval}_{direction}{distance}"
            new_file_path = file_path.parent / f"{new_name}.txt"
            
            file_path.rename(new_file_path)
            print(f"  ✓ {filename}.txt → {new_name}.txt")
            rename_count += 1
    
    print(f"Total files renamed: {rename_count}")

# Run renaming
print("="*80)
print("RENAMING OCTAHEDRON FILES TO NEW FORMAT")
print("="*80)

rename_files_in_directory(summaries_dir)
rename_files_in_directory(temp_dir)

print("\n" + "="*80)
print("Renaming complete!")
print("="*80)