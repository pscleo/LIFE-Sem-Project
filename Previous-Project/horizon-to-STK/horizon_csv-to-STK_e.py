# Script to generate STK Ephemeris (.e) files from JPL Horizons CSV output

## Usage:
# from command line:
# python horizon_csv-to-STK_e.py <input_csv_file> <output_e_file>

## Settings for the Horizons App
## https://ssd.jpl.nasa.gov/horizons/app.html#/
# 1. Ephemeris Type: Vector Table
# 3. Coordinate Center: Geocentric [code: 500]
# 4. Time Specifications: as needed, step size of 1hr is recommended for JWST
# 5. Table Settings: CSV, Delimiter: Comma
#    - Output Quantities: 2. State vector {x, y, z, vx, vy, vz}
#    - Statistical uncertainties: select as needed (none for JWST)
#    - Reference Frame: ICRF
#    - Reference plane: x-y axes of reference frame (equatorial or equatorial-aligned, inertial)
#    - Vector correction: geometric states
#    - Calendar type: Gregorian (changes apply only pre 1582-Oct-15)
#    - Output unity: km and s
#    - (Un-)check the following options
#      [x] Vector Labels: select as needed
#      [ ] Output TDB-UT
#      [x] CSV format
#      [x] Object summary: select as needed, this script should be able to deal with either option

# Script starts here
import pandas as pd
import sys
import os

def convert_horizons_csv_to_stk_e(input_file, output_file=None):
    """
    Convert JPL Horizons CSV output to STK Ephemeris (.e) file format.
    
    This function reads a CSV file generated by JPL Horizons (with $$SOE and $$EOE markers)
    and converts it to STK Ephemeris format suitable for use in AGI Systems Tool Kit.
    
    Args:
        input_file (str): Path to the input CSV file from JPL Horizons
        output_file (str, optional): Path to the output .e file. If None, uses the same
                                   name as input file but with .e extension
    
    Raises:
        ValueError: If $$SOE/$$EOE markers are not found or if the file format is invalid
        FileNotFoundError: If the input file does not exist
    
    Returns:
        None
    """
    
    # If no output file specified, use input filename with .e extension
    if output_file is None:
        base_name = os.path.splitext(input_file)[0]
        output_file = base_name + '.e'
    
    # Read the entire file as text first
    with open(input_file, 'r') as f:
        lines = f.readlines()
    
    # Find $$SOE marker (search from beginning, stop after finding)
    soe_index = None
    header_line_index = None
    
    for i, line in enumerate(lines):
        if '$$SOE' in line:
            soe_index = i
            # Look for the header line (should be 2 lines before $$SOE)
            if i >= 2:
                header_line_index = i - 2
            break  # Stop searching once we find $$SOE
    
    # Find $$EOE marker (search from end backwards)
    eoe_index = None
    for i in range(len(lines) - 1, -1, -1):
        if '$$EOE' in lines[i]:
            eoe_index = i
            break  # Stop searching once we find $$EOE
    
    if soe_index is None or eoe_index is None:
        raise ValueError("Could not find $$SOE and $$EOE markers in the file")
    
    # Extract the column header line to identify column positions
    if header_line_index is None:
        raise ValueError("Could not find column header line")
    
    header_line = lines[header_line_index].strip()
    # Remove leading '#' if present and split by comma
    header_line = header_line.lstrip('#').strip()
    column_names = [col.strip() for col in header_line.split(',')]
    
    # Find the index of the "Calendar Date (TDB)" column to remove
    calendar_date_index = None
    for i, col in enumerate(column_names):
        if 'Calendar Date' in col and 'TDB' in col:
            calendar_date_index = i
            break
    
    if calendar_date_index is None:
        raise ValueError("Could not find 'Calendar Date (TDB)' column")
    
    # Extract data lines (between $$SOE and $$EOE)
    data_lines = []
    for i in range(soe_index + 1, eoe_index):
        line = lines[i].strip()
        if line and not line.startswith('#') and not line.startswith('*'):
            # Remove leading '#' if present and split by comma
            line = line.lstrip('#').strip()
            data_parts = [part.strip() for part in line.split(',')]
            
            # Remove the Calendar Date column
            if len(data_parts) > calendar_date_index:
                data_parts.pop(calendar_date_index)
            
            # Convert comma-separated to space-delimited
            space_delimited_line = ' '.join(data_parts)
            data_lines.append(space_delimited_line)
    
    if not data_lines:
        raise ValueError("No data lines found between $$SOE and $$EOE")
    
    # Count the number of data lines
    num_lines = len(data_lines)
    
    # Create STK Ephemeris file content
    stk_content = []
    
    # STK Header
    stk_content.append("stk.v.13.0")
    stk_content.append("BEGIN Ephemeris")
    stk_content.append(f"   NumberOfEphemerisPoints {num_lines}")
    stk_content.append("   InterpolationMethod     Lagrange")
    stk_content.append("   InterpolationOrder      5")
    stk_content.append("   DistanceUnit            Kilometers")
    stk_content.append("   CentralBody             Earth")
    stk_content.append("   CoordinateSystem        ICRF")
    stk_content.append("   TimeFormat              JDTDB")
    stk_content.append("   EphemerisTimePosVel")
    
    # Add data lines
    for line in data_lines:
        stk_content.append(f"   {line}")
    
    # STK Footer
    stk_content.append("END Ephemeris")
    
    # Write to output file
    with open(output_file, 'w') as f:
        for line in stk_content:
            f.write(line + '\n')
    
    print(f"Successfully converted {input_file} to {output_file}")
    print(f"Number of ephemeris points: {num_lines}")

if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python horizon_csv-to-STK_e.py <input_csv_file> <output_e_file>")
        sys.exit(1)
    
    input_file = sys.argv[1]
    output_file = sys.argv[2]
    
    try:
        convert_horizons_csv_to_stk_e(input_file, output_file)
    except Exception as e:
        print(f"Error: {e}")
        sys.exit(1)